# Как открывать И закрывать позиции:
#
# "leader-follower"
#   Лидер (сторона с крупнейшей позицией) ставит POST_ONLY LIMIT.
#   После каждого фактического partial fill фолловеры параллельно
#   хеджируют ровно исполненный объём через MARKET + IOC.
#   При закрытии используется тот же механизм с reduce-only.
#
# "all-market"
#   Все кошельки открывают и закрывают позиции MARKET-ордерами.
#   Для текущих Standard-аккаунтов Lighter maker/taker-комиссия равна 0%.
#   Рыночные ордера всё равно могут терять на спреде и проскальзывании.
