"""Все пользовательские настройки Lighter Robinhood Delta-Neutral."""

# ============================================================
#  SETTINGS - LIGHTER ROBINHOOD DELTA-NEUTRAL
# ============================================================
# Заполни настройки под себя, затем перезапусти софт через npm start.
# ============================================================


# --- КОШЕЛЬКИ И ПОВТОРЫ ---

# Перемешивать кошельки перед каждым запуском.
# True = новый случайный порядок, и в каждом цикле кошельки распределяются
# по сторонам LONG/SHORT случайно.
# False = порядок из privatekeys.txt, стороны зависят только от баланса:
# крупнейшие кошельки всегда попадают в меньшую сторону группы.
SHUFFLE_WALLETS = True

# Какие кошельки участвуют в выбранном режиме. ID равен порядковому номеру
# приватного ключа в privatekeys.txt: первый ключ = 1, второй = 2 и так далее.
# ID нигде не показывается; пустые строки и комментарии не считаются.
# Форматы можно комбинировать:
#   ["5"]                  = только ID 5
#   [">5"]                 = ID 5 и больше
#   ["<5"]                 = ID 5 и меньше
#   [["1", "100"]]         = ID от 1 до 100 включительно
#   ["3", ["10", "13"], "20", ">100"] = комбинация правил
# [] = использовать все кошельки.
# Для режима 1 сумма LONG + SHORT в GROUP_CONFIGS должна совпадать с количеством
# кошельков, выбранных этим фильтром.
ID_FILTER = []

# Количество попыток торгового цикла, регистрации и Telegram при ошибке.
RETRY = 3

# Прокси задаются в input_data/proxies.txt. При запуске софт проверяет весь пул,
# пропускает нерабочие и распределяет рабочие по кругу. Один прокси может
# использоваться несколькими кошельками; пустой рабочий пул не останавливает софт.


# --- ЛОГИКА ИСПОЛНЕНИЯ ---

# Как открывать и закрывать позиции:
#   "leader-follower" = крупнейшая сторона ставит LIMIT, вторая сторона
#                       хеджирует фактические исполнения MARKET-ордерами.
#   "all-market"      = все кошельки исполняются MARKET + IOC параллельно.
EXECUTION_MODE = "all-market"


# --- ТОКЕНЫ ---

# Один токен: ["ETH"] - каждый цикл торгует только ETH.
# Несколько:  ["ETH", "SOL", "BTC"] - в каждом цикле случайно выбирается один.
# Для каждого активного токена обязательно добавь диапазон в TOKEN_LEVERAGE.
TOKENS_TO_TRADE = ["ETH"]


# --- РАЗМЕР ПОЗИЦИИ ---

# Какой процент доступного баланса использовать как маржу: [минимум, максимум].
# Для каждого кошелька значение выбирается случайно внутри диапазона.
# Пример: баланс 20 USDG x 90% x плечо 10 = позиция примерно на 180 USDG.
POSITION_PERCENT = [30, 100]

# Диапазон плеча для каждого токена: [минимум, максимум].
# Плечо выбирается отдельно для каждого кошелька с шагом 0.1x.
# Биржевой максимум читается из Lighter при запуске. Если настройка выше него,
# софт покажет ошибку до отправки ордеров, а не изменит значение молча.
TOKEN_LEVERAGE = {
    "ETH": [30, 50],
    # "SOL": [7, 10],
    # "BTC": [7, 10],
}


# --- ГРУППЫ ---

# Формат каждой группы: [количество LONG, количество SHORT].
# Сумма должна совпадать с количеством готовых торговых кошельков.
# Можно задать несколько вариантов одинакового размера - цикл выберет случайный.
# 2 кошелька: [[1, 1]]
# 3 кошелька: [[2, 1], [1, 2]]
# 5 кошельков: [[3, 2], [2, 3]]
# Направления дополнительно случайно меняются местами перед распределением объёма.
GROUP_CONFIGS = [[5, 4]]


# --- ЦЕНА И ОРДЕРА ---

# Максимальный спред для входа, в процентах.
# 0.03 означает 0.03%, не 3%. Если спред выше, софт ждёт его сужения.
MAX_SPREAD = 0.03

# Допустимое проскальзывание MARKET + IOC, в процентах.
# 0.02 означает предельную цену на 0.02% хуже текущей стороны стакана.
SLIPPAGE = 0.02


# --- УДЕРЖАНИЕ И ЦИКЛЫ ---

# Время удержания позиции в минутах: [минимум, максимум].
# Случайное значение выбирается отдельно для каждого цикла.
# [720, 1440] = от 12 до 24 часов.
# [0, 0] = держать без ограничения до запуска режима 2 в другом процессе.
HOLD_MINUTES = [1, 5]

# Количество полных циклов: открытие -> удержание -> закрытие.
TRADES_COUNT = 100


# --- ЗАДЕРЖКИ И ОПРОС БИРЖИ ---

# Пауза между завершёнными циклами, в секундах: [минимум, максимум].
# [0, 0] полностью отключает паузу.
DELAY_BETWEEN_TRADES = [10, 30]

# Пауза между подготовкой кошельков перед торговым запуском, в секундах.
# Ордеры внутри дельта-нейтральной пары всё равно отправляются параллельно,
# чтобы эта задержка не создавала открытую направленную позицию.
# [0, 0] полностью отключает паузу.
DELAY_BETWEEN_WALLETS = [3, 8]

# Как часто проверять спред, удержание, повтор стратегии и появление fill,
# в секундах. Частичные maker-fill используют отдельный быстрый интервал ниже.
POLL_INTERVAL_SEC = 5


# --- ПАРНОЕ ИСПОЛНЕНИЕ ---
# Эти настройки используются только при EXECUTION_MODE = "leader-follower".

# Как часто проверять, исполнилась ли хотя бы часть LIMIT-ордера лидера.
# Меньше значение = быстрее хедж, но больше запросов к бирже. Миллисекунды.
HEDGE_POLL_INTERVAL_MS = 300

# Как часто сравнивать LIMIT-ордер лидера с текущей лучшей ценой. Секунды.
MAKER_REQUOTE_INTERVAL_SEC = 20

# На сколько процентов должна уйти лучшая цена, чтобы переставить LIMIT-ордер.
# 0.03 означает движение цены на 0.03%.
MAKER_REQUOTE_THRESHOLD_PERCENT = 0.03

# Сколько максимум ждать LIMIT-ордер лидера. После таймаута бот отменит его и
# закроет оставшийся риск MARKET-ордерами. Секунды.
MAX_MAKER_WAIT_SEC = 180

# Сколько раз повторять MARKET-хедж, если он не исполнился полностью.
MAX_HEDGE_RETRIES = 3


# --- РЕЖИМ 4: РЕГИСТРАЦИЯ + ПОПОЛНЕНИЕ USDG ---

# True = депозитить весь доступный USDG-баланс каждого кошелька.
# False = использовать случайную сумму из DEPOSIT_AMOUNT.
DEPOSIT_ALL = True

# Целая сумма депозита USDG: [минимум, максимум].
# Если значения различаются, случайная сумма выбирается с шагом 1 USDG.
# Работает только при DEPOSIT_ALL = False.
DEPOSIT_AMOUNT = [10, 10]


# --- РЕЖИМ 5: ВЫВОД USDG ---

# True = вывести весь доступный USDG-баланс Lighter на исходный кошелёк.
# False = выводить случайную сумму из WITHDRAW_AMOUNT.
# Перед выводом все позиции должны быть закрыты через режим 2.
WITHDRAW_ALL = True

# Сумма вывода USDG: [минимум, максимум].
# Для каждого кошелька значение выбирается отдельно внутри диапазона.
# Работает только при WITHDRAW_ALL = False.
WITHDRAW_AMOUNT = [10, 10]
