"""Пользовательские настройки Lighter Robinhood Delta-Neutral."""

# После изменений перезапусти софт через npm start.


# ============================================================
#  КОШЕЛЬКИ
# ============================================================

# True = каждому кошельку обязателен отдельный рабочий прокси.
# Если прокси отсутствует, повторяется или не отвечает, запуск остановится.
STRICT_PROXY_ISOLATION = True

# Перемешивать порядок кошельков перед каждым запуском.
SHUFFLE_WALLETS = True

# Сколько раз повторять неудачный торговый цикл и отправку в Telegram.
RETRY = 3


# ============================================================
#  ИСПОЛНЕНИЕ ОРДЕРОВ
# ============================================================

# "all-market" = все кошельки открываются и закрываются MARKET-ордерами.
# "leader-follower" = лидер ставит LIMIT, остальные хеджируют его исполнения MARKET.
EXECUTION_MODE = "all-market"

# Рынки для торговли. В каждом цикле случайно выбирается один символ из списка.
TOKENS_TO_TRADE = ["ETH"]


# ============================================================
#  РАЗМЕР ПОЗИЦИЙ
# ============================================================

# Процент доступного баланса, используемый как маржа: [минимум, максимум].
# Пример: 20 USDG x 90% x плечо 10 = позиция примерно на 180 USDG.
POSITION_PERCENT = [85, 100]

# Диапазон плеча для каждого рынка. Значение выбирается отдельно для кошелька.
TOKEN_LEVERAGE = {
    "ETH": [7, 10],
}

# Группы кошельков в формате [[LONG, SHORT], ...].
# [[3, 2]] означает три кошелька с одной стороны и два с противоположной.
# Направления LONG/SHORT случайно меняются местами между циклами.
GROUP_CONFIGS = [[3, 2]]


# ============================================================
#  ЦЕНА ВХОДА
# ============================================================

# Максимальный спред для входа, в процентах. 0.03 означает 0.03%, не 3%.
MAX_SPREAD = 0.03

# Допустимое проскальзывание MARKET-ордера, в процентах.
SLIPPAGE = 0.02


# ============================================================
#  ЦИКЛЫ
# ============================================================

# Время удержания позиции в минутах: [минимум, максимум].
# [720, 1440] = от 12 до 24 часов. [0, 0] = держать до запуска режима 2.
HOLD_MINUTES = [720, 1440]

# Количество циклов: открытие -> удержание -> закрытие.
TRADES_COUNT = 3

# Пауза между завершёнными циклами, в секундах: [минимум, максимум].
DELAY_BETWEEN_TRADES = [10, 30]


# ============================================================
#  LEADER-FOLLOWER
# ============================================================
# Эти параметры используются только при EXECUTION_MODE = "leader-follower".

# Частота проверки исполнений LIMIT-ордера лидера, в миллисекундах.
HEDGE_POLL_INTERVAL_MS = 300

# Через сколько секунд проверять, нужно ли переставить LIMIT-ордер.
MAKER_REQUOTE_INTERVAL_SEC = 20

# Минимальное отклонение цены для перестановки LIMIT-ордера, в процентах.
MAKER_REQUOTE_THRESHOLD_PERCENT = 0.03

# Максимальное ожидание исполнения LIMIT-ордера, в секундах.
MAX_MAKER_WAIT_SEC = 180

# Количество повторов недостающего MARKET-хеджа.
MAX_HEDGE_RETRIES = 3


# ============================================================
#  РЕЖИМ 4: РЕФЕРАЛ + ДЕПОЗИТ USDG
# ============================================================

# True = депозитить весь доступный USDG-баланс каждого кошелька.
# False = использовать случайную сумму из DEPOSIT_AMOUNT.
DEPOSIT_ALL = True

# Сумма депозита USDG: [минимум, максимум]. Работает при DEPOSIT_ALL = False.
DEPOSIT_AMOUNT = [10, 10]
